            if(posix_spawn_file_actions_adddup2(&actions,in[0],STDIN_FILENO)!=0 ||
               posix_spawn_file_actions_adddup2(&actions,out[1],STDOUT_FILENO)!=0 ||
               posix_spawn_file_actions_adddup2(&actions,err,STDERR_FILENO)!=0)
                throw std::runtime_error("MCP stdio spawn redirection failed");
            for(int fd:{in[0],in[1],out[0],out[1],err})if(posix_spawn_file_actions_addclose(&actions,fd)!=0)
                throw std::runtime_error("MCP stdio spawn close setup failed");
